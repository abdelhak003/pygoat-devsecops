@csrf_exempt
def mitre_lab_25_api(request):
    if request.method == "POST":
        expression = request.POST.get('expression') or ''
        # The vulnerable version returned eval(expression): any Python code ran on the server
        # (CWE-95). Only plain arithmetic is computed now, through an AST allowlist.
        try:
            result = safe_calculate(expression)
        except UnsafeExpression:
            return JsonResponse({'result': explain_eval(expression), 'evaluated': False})
        except (ArithmeticError, ValueError) as exc:
            return JsonResponse({'result': f"Math error: {exc}", 'evaluated': False})
        return JsonResponse({'result': result, 'evaluated': True})
    else:
        return redirect('/mitre/25/lab/')


