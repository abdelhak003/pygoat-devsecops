def csrf_lab_jwt_key():
    """Signing key of the CSRF lab cookie (previously a hard-coded string literal).

    Never committed: derived from the environment-provided SECRET_KEY with a purpose-specific
    salt (key separation, the same mechanism as django.core.signing), so it differs from
    SECRET_KEY and from every other derived key, and is identical in all Gunicorn workers.
    """
    return salted_hmac("pygoat.mitre.csrf_lab.jwt", "jwt-signing-key", algorithm="sha256").hexdigest()

